function sortProducts(products, sortBy) {
    const sorted = [...products];
    
    switch(sortBy) {
        case 'price-low':
            return sorted.sort((a, b) => (Number.isFinite(a.price) ? a.price : Number.POSITIVE_INFINITY) - (Number.isFinite(b.price) ? b.price : Number.POSITIVE_INFINITY));
        case 'price-high':
            return sorted.sort((a, b) => {
                if (!Number.isFinite(a.price)) return 1;
                if (!Number.isFinite(b.price)) return -1;
                return b.price - a.price;
            });
        default:
            return sorted;
    }
}

